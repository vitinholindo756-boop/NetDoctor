function T([string]$s) {
    if ($script:LangCode -eq 'pt' -or [string]::IsNullOrEmpty($s)) { return $s }
    $d = $script:LangData[$script:LangCode]
    if ($d -and $d.ContainsKey($s)) { return [string]$d[$s] }
    $s
}

# 'auto' segue o idioma do Windows (portugues, ingles ou espanhol; outros caem em ingles).
function Resolve-LangCode([string]$pref) {
    if ($pref -eq 'pt' -or $pref -eq 'en' -or $pref -eq 'es') { return $pref }
    $c = 'en'
    try {
        $iso = (Get-Culture).TwoLetterISOLanguageName
        if ($iso -eq 'pt') { $c = 'pt' } elseif ($iso -eq 'es') { $c = 'es' }
    } catch { }
    $c
}

$script:Translating = $false
$script:OrigItems = @{}
$script:OrigText = New-Object 'System.Collections.Generic.Dictionary[object,string]'

# Texto original (em portugues) de um controle/coluna, guardado na primeira passada.
function Get-OrigText($obj) {
    if (-not $script:OrigText.ContainsKey($obj)) { $script:OrigText[$obj] = [string]$obj.Text }
    $script:OrigText[$obj]
}

# Nome da aba em portugues (para a logica que depende do nome da aba, mesmo com a interface traduzida).
function Get-TabKey($page) {
    if (-not $page) { return '' }
    Get-OrigText $page
}

# Troca o texto dos itens de uma lista (a selecao e mantida; o flag impede que os eventos de selecao reajam).
function Translate-Combo($c, [string]$id) {
    $sel = $c.SelectedIndex
    $script:Translating = $true
    try {
        for ($i = 0; $i -lt $c.Items.Count; $i++) {
            $key = $id + ':' + $i
            if (-not $script:OrigItems.ContainsKey($key)) { $script:OrigItems[$key] = [string]$c.Items[$i] }
            $c.Items[$i] = (T $script:OrigItems[$key])
        }
        $c.SelectedIndex = $sel
    } finally { $script:Translating = $false }
}

function Translate-Control($c) {
    $tag = ''
    if ($c.Tag -is [string]) { $tag = [string]$c.Tag }
    if ($tag -eq 'keep') { return }
    $dinamico = ($tag -eq 'info' -or $tag -eq 'muted' -or $tag -eq 'verdict' -or $tag -eq 'surface')
    if (-not $dinamico -and ($c -is [System.Windows.Forms.Button] -or $c -is [System.Windows.Forms.CheckBox] -or $c -is [System.Windows.Forms.TabPage] -or $c -is [System.Windows.Forms.Label])) {
        $o = Get-OrigText $c
        if ($o) { $c.Text = (T $o) }
    }
    if ($c -is [System.Windows.Forms.ListView]) {
        foreach ($col in $c.Columns) { $o = Get-OrigText $col; if ($o) { $col.Text = (T $o) } }
    }
    if ($c -is [System.Windows.Forms.ComboBox] -and $tag -eq 'i18n') { Translate-Combo $c $c.Name }
    foreach ($ch in $c.Controls) { Translate-Control $ch }
}
